#!/usr/bin/env python3
"""
generate_dataset_summary.py — Print a compact statistical summary of
dataset/, suitable for pasting into an LLM context alongside the
narrative files instead of the full raw structured data (see
prompts/prompt_design_notes.md, "Context-window management").

Run: python3 scripts/generate_dataset_summary.py
"""
from __future__ import annotations

import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DATASET_DIR = REPO_ROOT / "dataset"


def summarize_application_logs():
    print("\n## application_logs.jsonl")
    counts_by_evidence = defaultdict(int)
    counts_by_error_class = defaultdict(int)
    with open(DATASET_DIR / "application_logs.jsonl", encoding="utf-8") as f:
        rows = [json.loads(line) for line in f if line.strip()]
    for r in rows:
        counts_by_evidence[r["evidence_id"]] += 1
        counts_by_error_class[r["error_class"] or "(none)"] += 1
    print(f"Total records: {len(rows)}")
    print("By evidence_id:", dict(sorted(counts_by_evidence.items())))
    print("By error_class:", dict(sorted(counts_by_error_class.items())))


def summarize_csv(filename: str, group_field: str = "evidence_id"):
    print(f"\n## {filename}")
    path = DATASET_DIR / filename
    with open(path, encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    counts = defaultdict(int)
    for r in rows:
        counts[r.get(group_field, "(none)")] += 1
    print(f"Total rows: {len(rows)}")
    print(f"By {group_field}:", dict(sorted(counts.items())))


def summarize_payment_metrics():
    summarize_csv("payment_metrics.csv")
    print("\n### Provider contrast (ProviderAlpha vs ProviderBeta), full incident day")
    path = DATASET_DIR / "payment_metrics.csv"
    with open(path, encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    by_provider = defaultdict(lambda: {"attempts": 0, "timeouts": 0, "authorized": 0})
    for r in rows:
        p = by_provider[r["provider"]]
        p["attempts"] += int(r["attempts"])
        p["timeouts"] += int(r["timeouts"])
        p["authorized"] += int(r["authorized"])
    for provider, agg in sorted(by_provider.items()):
        rate = agg["timeouts"] / agg["attempts"] if agg["attempts"] else 0
        print(f"  {provider}: attempts={agg['attempts']} timeouts={agg['timeouts']} "
              f"(rate={rate:.3f}) authorized={agg['authorized']}")


def summarize_hourly_kpis():
    summarize_csv("hourly_kpis.csv", group_field="region")
    print("\n### Authorization success rate: baseline vs incident day, by region")
    path = DATASET_DIR / "hourly_kpis.csv"
    with open(path, encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    by_key = defaultdict(list)
    for r in rows:
        by_key[(r["date"], r["region"])].append(float(r["auth_success_rate"]))
    for (date, region), rates in sorted(by_key.items()):
        print(f"  {date} {region}: avg={sum(rates)/len(rates):.4f} min={min(rates):.4f} max={max(rates):.4f}")


def main() -> int:
    print("# Dataset Summary (generated by scripts/generate_dataset_summary.py)")
    summarize_application_logs()
    summarize_csv("api_gateway_logs.csv")
    summarize_hourly_kpis()
    summarize_payment_metrics()
    summarize_csv("customer_feedback.csv")
    summarize_csv("campaign_schedule.csv")
    return 0


if __name__ == "__main__":
    sys.exit(main())
